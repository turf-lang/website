// Builds src/content/docs/errors/*.mdx from the compiler's diagnostic-code registry
// (IF-3): share/turf/diagnostic-registry.json in a release archive, or what
// `turfc --registry-json` prints. A copy is kept at src/data/diagnostic-registry.json.
//
//   node scripts/convert-errors.mjs [--registry <file>]   write the pages
//   node scripts/convert-errors.mjs --check               fail if a page is stale or missing
//
// `pnpm build` runs --check first, so the site cannot ship pages that disagree with the
// registry. Each explanation is the text `turf --explain` prints: the first line is the
// title, then paragraphs, and code indented by four spaces. The text is kept verbatim;
// indented code becomes a <Code> block, and `{`, `<` in prose are escaped for MDX. Also
// writes errors/index.mdx (a table of every code).

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const args = process.argv.slice(2);
const check = args.includes("--check");
const at = args.indexOf("--registry");
const REGISTRY = at >= 0 ? args[at + 1] : "src/data/diagnostic-registry.json";
const registry = JSON.parse(readFileSync(REGISTRY, "utf8"));
if (registry.format !== 1) {
    console.error(`convert-errors: ${REGISTRY} is registry format ${registry.format}; this script reads format 1`);
    process.exit(1);
}
const OUT = "src/content/docs/errors";
if (!check) mkdirSync(OUT, { recursive: true });
const pages = new Map();

// Escape what MDX would read as JSX or an expression, outside `inline code`.
const escape = (line) =>
    line
        .split(/(`[^`]*`)/)
        .map((part, i) => (i % 2 ? part : part.replace(/\{/g, "\\{").replace(/\}/g, "\\}").replace(/</g, "&lt;")))
        .join("");

// One line under the title for what the registry says beyond the text.
const facts = (c) => {
    const parts = [];
    if (c.retired) parts.push("Retired: the compiler no longer reports this code.");
    else if (c.severity === "warning")
        parts.push(c.default_level === "allow" ? "A warning, off unless its lint level is raised." : "A warning, on by default.");
    if (c.since !== "2.0") parts.push(`Since TurfLang ${c.since}.`);
    return parts.join(" ");
};

const codes = registry.codes.filter((c) => c.explanation_source === "code" && c.explanation).sort((a, b) => a.code.localeCompare(b.code));
const rows = [];
for (const entry of codes) {
    const code = entry.code;
    const n = code.slice(1);
    const lines = entry.explanation.replace(/\r\n/g, "\n").trimEnd().split("\n");
    const title = lines[0].trim().replace(/`/g, "");
    const body = [];
    for (let i = 2; i < lines.length; ) {
        if (/^ {4}/.test(lines[i])) {
            const block = [];
            while (i < lines.length && (/^ {4}/.test(lines[i]) || lines[i] === "")) block.push(lines[i++].replace(/^ {4}/, ""));
            while (block.at(-1) === "") block.pop();
            body.push("", `<Code title="Example">`, "```turf", ...block, "```", "</Code>", "");
        } else {
            body.push(escape(lines[i++]));
        }
    }
    const first = body.find((l) => l.trim() && !l.startsWith("<") && !l.startsWith("```")) ?? title;
    const description = first.replace(/[`*]/g, "").replace(/\\([{}])/g, "$1").replace(/&lt;/g, "<").split(/(?<=[.!?])\s/)[0].slice(0, 220);
    const text = `---
title: ${JSON.stringify(`${code}: ${title}`)}
description: ${JSON.stringify(`What compiler ${entry.severity} ${code} means, and how to fix it.`)}
order: ${Number(n)}
---

{/* Generated by scripts/convert-errors.mjs from the diagnostic registry of turfc ${registry.turfc}. */}
${facts(entry) ? `\n${facts(entry)}\n` : ""}
${body.join("\n").replace(/\n{3,}/g, "\n\n").trim()}

Run \`turf --explain ${code}\` in a terminal to read this again.
`;
    pages.set(`${code.toLowerCase()}.mdx`, text);
    rows.push(`| [${code}](/docs/errors/${code.toLowerCase()}/) | ${title.replace(/\|/g, "\\|").replace(/</g, "&lt;")} |`);
}

pages.set(
    "index.mdx",
    `---
title: "Error codes"
description: "Every error code the Turf compiler can print, with what it means and how to fix it."
lead: "When the compiler stops you, it prints a code such as E008. Each code has its own page here that explains, in plain words, what went wrong and how to fix it."
order: 4
---

{/* Generated by scripts/convert-errors.mjs from the diagnostic registry. */}

## How to use this page

A compiler error looks like this. The code (**E060**) is in square brackets on the first line:

<Diagnostic file="apples.tr">
\`\`\`turf
fn main(): int {
    immut apples = 3;
    apples = 4;
    return 0;
}
\`\`\`
\`\`\`text
apples.tr (1 error)

── error at line 3, col 12 [E060 · declaration]

  Oops! You can't change the value of 'apples' because it's immutable.
  Note: declared immutable here (line 2, col 5)

  Hint: If you need to change its value later, declare it with 'mutable' instead of 'immutable'.

  3 │     apples = 4;
    │            ^ Here!

  Run \`turf --explain E060\` for more details.
\`\`\`
</Diagnostic>

Find the code below, or run \`turf --explain E060\` in a terminal. The command line and the diagnostic format are described in [CLI & Diagnostics](/docs/tooling/cli-and-diagnostics/#part-2--diagnostics-and-error-codes).

## All ${rows.length} codes

| Code | What it means |
|---|---|
${rows.join("\n")}
`,
);

if (check) {
    const problems = [];
    for (const [name, text] of pages) {
        const path = join(OUT, name);
        if (!existsSync(path)) problems.push(`${path} is missing`);
        else if (readFileSync(path, "utf8") !== text) problems.push(`${path} is stale`);
    }
    for (const name of existsSync(OUT) ? readdirSync(OUT) : [])
        if (!pages.has(name)) problems.push(`${join(OUT, name)} has no code in the registry`);
    if (problems.length) {
        console.error(problems.join("\n"));
        console.error(`convert-errors: ${problems.length} problem(s); run node scripts/convert-errors.mjs to regenerate from ${REGISTRY}`);
        process.exit(1);
    }
    console.log(`convert-errors: ${pages.size - 1} error pages match ${REGISTRY} (turfc ${registry.turfc})`);
} else {
    for (const [name, text] of pages) writeFileSync(join(OUT, name), text);
    console.log(`convert-errors: wrote ${pages.size} pages from ${REGISTRY}`);
}
